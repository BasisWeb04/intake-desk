import { readFileSync, writeFileSync } from "node:fs";
import { formatTable, pct, scoreCases, type EvalCase, type EvalResult } from "./score";

export interface RunOptions {
  casesPath: string;
  outPath: string;
  date?: Date;
}

function assertCases(value: unknown): asserts value is EvalCase[] {
  if (!Array.isArray(value) || value.length === 0) throw new Error("cases file must be a non-empty array");
  for (const c of value) {
    if (typeof c?.id !== "string" || typeof c?.text !== "string" || typeof c?.expected !== "object" || !Array.isArray(c?.tags)) {
      throw new Error(`malformed case: ${JSON.stringify(c).slice(0, 80)}`);
    }
  }
}

export function renderReport(result: EvalResult, date: Date): string {
  const missLines = result.misses.map(
    (m) => `| ${m.id} | ${m.field} | ${m.expected ?? "(none)"} | ${m.got ?? "(none)"} |`,
  );
  return [
    "# Eval results: rules engine",
    "",
    `Run date (UTC): ${date.toISOString().slice(0, 10)}`,
    `Cases: ${result.cases}`,
    "Engine: safety rules, then RuleExtractor (the default engine the live demo runs).",
    "Generated by `npm run eval`; do not edit by hand.",
    "",
    formatTable(result),
    "",
    `Authored cases (written alongside the rules): ${result.groups.authored.correct}/${result.groups.authored.total} fields (${pct(result.groups.authored.correct, result.groups.authored.total)})`,
    `Held-out cases (written after the rules were frozen): ${result.groups.holdout.correct}/${result.groups.holdout.total} fields (${pct(result.groups.holdout.correct, result.groups.holdout.total)})`,
    "",
    `Safety recall: ${result.safetyRecall.hit} of ${result.safetyRecall.total} (${pct(result.safetyRecall.hit, result.safetyRecall.total)})`,
    `False safety flags on non-safety cases: ${result.falseSafety.flagged.length} of ${result.falseSafety.total}` +
      (result.falseSafety.flagged.length ? ` (${result.falseSafety.flagged.join(", ")})` : ""),
    "",
    "## Misses",
    "",
    result.misses.length === 0 ? "None." : ["| Case | Field | Expected | Got |", "| --- | --- | --- | --- |", ...missLines].join("\n"),
    "",
  ].join("\n");
}

export function runEval(options: RunOptions): EvalResult {
  const parsed: unknown = JSON.parse(readFileSync(options.casesPath, "utf8"));
  assertCases(parsed);
  const result = scoreCases(parsed);
  writeFileSync(options.outPath, renderReport(result, options.date ?? new Date()), "utf8");
  return result;
}
